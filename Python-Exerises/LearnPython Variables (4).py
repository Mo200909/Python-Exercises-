student = int(input("Enter your student grade: "))
if student == 9:
    print(" You are in grade 9")
elif student  == 10:
    print(" You are in grade 10")
elif student == 11:
    print(" You are in grade 11")
elif student == 12:
    print(" You are in grade 12")
else:
    print(" You are in elementary school or middle school")